#!/usr/bin/env python3
"""Generate the mechanical views so nobody hand-writes them.

At 300 systems, a per-system `views.dsl` plus a matching `!include` line is 600
pieces of identical boilerplate. This generates the standard context view for
every software system, and one landscape per portfolio category, into
`models/shared/views-generated.dsl`.

Each portfolio landscape shows the portfolio's systems plus the systems in
other portfolios they connect to, and gets its own portal page
(`workspace/docs/02-portfolio-N-<name>.gen.md`) listing both.

Hand-written views still win: a system with its own `views.dsl` is skipped here,
so anything needing custom scoping or layout stays under the author's control.

Scale note (measured — see docs/architecture-as-code/scale.md): landscape views
degrade catastrophically past ~60 elements, so a category holding more than
that must be split before its landscape is usable.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from dsl_model import ROOT, parse_model

OUTPUT = ROOT / "models/shared/views-generated.dsl"
PAGES_DIR = ROOT / "workspace/docs"
PAGE_HEADER = "<!-- GENERATED by scripts/generate_views.py — do not edit. -->"
# The diagram legend is authored once, on the Enterprise Landscape page.
LEGEND_SOURCE = PAGES_DIR / "02-enterprise-landscape.md"
LEGEND_RE = re.compile(r"<!-- legend:start.*?-->\n(.*?)<!-- legend:end -->", re.S)

# Same tab strip as the Enterprise Landscape page (which mirrors the native
# per-system page tabs): both variants of the landscape, toggled in place.
TABS = """\
<div class="tabs mt-3">
  <ul id="landscape-tabs" class="is-flex-wrap-wrap is-flex-shrink-1 is-flex-grow-0">
    <li class="is-active" data-target="landscape-with-people"><a class="is-active">With people</a></li>
    <li data-target="landscape-systems-only"><a>Systems only</a></li>
  </ul>
</div>
<div class="content p-3" id="landscape-with-people">
  <img src="embed:{people_key}" alt="{category} landscape with people">
</div>
<div class="content p-3" id="landscape-systems-only" style="display: none;">
  <img src="embed:{systems_key}" alt="{category} landscape, systems only">
</div>
<script>
  document.querySelectorAll('#landscape-tabs li').forEach(function (tab) {{
    tab.addEventListener('click', function () {{
      document.querySelectorAll('#landscape-tabs li').forEach(function (t) {{
        t.classList.remove('is-active');
        t.querySelector('a').classList.remove('is-active');
        document.getElementById(t.dataset.target).style.display = 'none';
      }});
      tab.classList.add('is-active');
      tab.querySelector('a').classList.add('is-active');
      document.getElementById(tab.dataset.target).style.display = '';
    }});
  }});
</script>"""
SYSTEMS_DIR = ROOT / "models/enterprise/systems"
SOLUTIONS_DIR = ROOT / "models/solutions"

# Above this many elements a landscape stops being readable and starts being
# slow; the spike measured 60 fine, 195 unusable, 300 unrenderable.
LANDSCAPE_WARN_THRESHOLD = 60


def hand_written_context_views() -> set[str]:
    """Identifiers that already have an author-written systemContext view.

    Checked per *view*, not per element: a solution can hand-write its container
    and deployment views and still receive the standard generated context view.
    """
    written = set()
    for views_file in list(ROOT.glob("models/**/views.dsl")) + [
        ROOT / "workspace/workspace.dsl"
    ]:
        if not views_file.exists():
            continue
        for match in re.finditer(r"^\s*systemContext\s+(\w+)", views_file.read_text(), re.M):
            written.add(match.group(1))
    return written


def portfolio_of(system, categories: list[str]) -> str:
    return next((t for t in system.tags if t in categories), "(none)")


def system_links(model) -> dict[tuple[str, str], list[str]]:
    """System-to-system connections, with the descriptions behind each.

    Solution relationships are declared between containers and components;
    each is lifted to the software systems that own its two ends, as
    Structurizr's implied relationships do on a landscape view. When the same
    connection is modelled at several levels (a container call and the
    component call inside it), only the highest-level descriptions are kept.
    """
    def depth(identifier: str) -> int:
        hops = 0
        while identifier in model.parents:
            identifier = model.parents[identifier]
            hops += 1
        return hops

    best: dict[tuple[str, str], tuple[int, list[str]]] = {}
    for rel in model.relationships:
        source = model.owning_system(rel.source)
        destination = model.owning_system(rel.destination)
        if not (source and destination and source != destination):
            continue
        level = depth(rel.source) + depth(rel.destination)
        current = best.get((source, destination))
        if current is None or level < current[0]:
            best[(source, destination)] = (level, [])
        elif level > current[0]:
            continue
        descriptions = best[(source, destination)][1]
        if rel.description and rel.description not in descriptions:
            descriptions.append(rel.description)
    return {pair: descriptions for pair, (_, descriptions) in best.items()}


def page_slug(name: str) -> str:
    """The site generator's URL segment for a page or software system."""
    return name.lower().replace(" ", "-")


def legend() -> str:
    match = LEGEND_RE.search(LEGEND_SOURCE.read_text())
    if not match:
        raise SystemExit(
            f"{LEGEND_SOURCE.relative_to(ROOT)}: legend:start / legend:end "
            "markers not found — the portfolio pages copy the legend from there."
        )
    return match.group(1).strip()


def portfolio_page(category: str, key: str, members, connections, systems) -> str:
    """Portal page for one portfolio: its landscapes, systems and connections."""
    # The site generator resolves relative links from the branch root
    # (/<branch>/), not from the page, and rewrites them to match.
    def link(system) -> str:
        return f"[{system.name}]({page_slug(system.name)}/)"

    lines = [
        f"## {category} Landscape",
        "",
        PAGE_HEADER,
        "",
    ]
    if not members:
        lines += [f"No systems are in the **{category}** portfolio yet.", ""]
        return "\n".join(lines)

    intro = f"The systems in the **{category}** portfolio"
    if connections:
        intro += (", together with the systems in other portfolios they connect "
                  "to — those are drawn in their own portfolio's colour and boundary")
    lines += [
        f"{intro}. _With people_ adds the people who use this portfolio's "
        "systems. The whole estate is on the "
        "[Enterprise Landscape](enterprise-landscape/) page.",
        "",
        "### Reading the diagrams",
        "",
        legend(),
        "",
        TABS.format(category=category, people_key=key,
                    systems_key=f"{key}-SystemsOnly"),
        "",
        "### Systems in this portfolio",
        "",
        "| System | Capability | Owner | Lifecycle | Criticality |",
        "|---|---|---|---|---|",
    ]
    for system in sorted(members, key=lambda s: s.name):
        p = system.properties.get
        lines.append(
            f"| {link(system)} | {p('capability', '-')} | {p('owner', '-')} "
            f"| {p('lifecycle', '-')} | {p('criticality', '-')} |"
        )
    lines.append("")

    lines += ["### Connections to other portfolios", ""]
    if not connections:
        lines += ["None — this portfolio's systems only connect to each other.", ""]
        return "\n".join(lines)
    lines += [
        "| From | To | Other portfolio | Description |",
        "|---|---|---|---|",
    ]
    for (source, destination), descriptions, other in connections:
        lines.append(
            f"| {link(systems[source])} | {link(systems[destination])} "
            f"| {other} | {'; '.join(descriptions) or '-'} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    model = parse_model()
    vocabulary = json.loads((ROOT / "models/shared/vocabulary.json").read_text())
    categories = vocabulary["portfolioCategories"]

    lines = [
        "# GENERATED by scripts/generate_views.py — do not edit.",
        "# Standard context views for every system, plus one landscape per",
        "# portfolio category. Elements with their own views.dsl are skipped.",
        "",
    ]

    authored = hand_written_context_views()
    generated = skipped = 0
    for system in sorted(model.systems, key=lambda s: s.name):
        if system.identifier in authored:
            skipped += 1
            continue
        key = system.name.replace(" ", "")
        lines += [
            f'systemContext {system.identifier} "{key}-Context" '
            f'"{system.name} and its direct dependencies." {{',
            "    include *",
            "    autoLayout lr",
            "}",
            "",
        ]
        generated += 1

    # Two landscapes per portfolio category, like the Enterprise Landscape:
    # with people, and systems only. Both show the category's systems (by tag)
    # plus any system in another portfolio that one of them connects to; the
    # first adds the people who use the category's systems.
    systems = {s.identifier: s for s in model.systems}
    links = system_links(model)
    for old in PAGES_DIR.glob("02-portfolio-*.gen.md"):
        old.unlink()  # a renamed or removed category must not leave a page behind
    sizes = {}
    for number, category in enumerate(categories, start=1):
        key = category.replace(" ", "")
        members = [s for s in model.systems if category in s.tags]
        member_ids = {s.identifier for s in members}
        connections = sorted(
            (
                (pair, descriptions,
                 portfolio_of(systems[pair[1] if pair[0] in member_ids else pair[0]],
                              categories))
                for pair, descriptions in links.items()
                if (pair[0] in member_ids) != (pair[1] in member_ids)
            ),
            key=lambda c: (systems[c[0][0]].name, systems[c[0][1]].name),
        )
        neighbours = sorted(
            {i for (pair, _, _) in connections for i in pair} - member_ids,
            key=lambda i: systems[i].name,
        )
        people = sorted({
            person
            for rel in model.relationships
            for person, other in ((rel.source, rel.destination),
                                  (rel.destination, rel.source))
            if person in model.people and model.owning_system(other) in member_ids
        })
        sizes[category] = len(members) + len(neighbours) + len(people)

        system_includes = [f'    include "element.tag=={category}"']
        if neighbours:
            system_includes.append(f"    include {' '.join(neighbours)}")
        lines += [
            f'systemLandscape "{key}" "{category} — the portfolio, its users and '
            f'the systems it connects to." {{',
            *system_includes,
        ]
        if people:
            lines.append(f"    include {' '.join(people)}")
        lines += [
            "    autoLayout tb",
            "}",
            "",
            f'systemLandscape "{key}-SystemsOnly" "{category} — the portfolio and '
            f'the systems it connects to, without people." {{',
            *system_includes,
            "    autoLayout lr",
            "}",
            "",
        ]

        page = PAGES_DIR / f"02-portfolio-{number}-{page_slug(category)}.gen.md"
        page.write_text(portfolio_page(category, key, members, connections, systems))

    OUTPUT.write_text("\n".join(lines))
    print(
        f"wrote {OUTPUT.relative_to(ROOT)}: {generated} context views generated, "
        f"{skipped} hand-written skipped, {len(categories)} category landscapes "
        f"and pages"
    )

    oversized = {c: n for c, n in sizes.items() if n > LANDSCAPE_WARN_THRESHOLD}
    for category, count in oversized.items():
        print(
            f"  ! '{category}' shows {count} systems — landscapes above "
            f"{LANDSCAPE_WARN_THRESHOLD} become unreadable and slow to render. "
            f"Split it into sub-categories.",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
