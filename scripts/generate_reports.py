#!/usr/bin/env python3
"""Generate inventory reports from model properties.

Outputs (Markdown, rendered into the portal as documentation):
  workspace/docs/90-technology-inventory.gen.md
  workspace/docs/91-interface-catalogue.gen.md
  workspace/docs/92-component-inventory.gen.md   (from the SBOMs)
  <system or solution>/docs/90-sbom.gen.md       (one per asset with SBOMs)

*.gen.md files are generated artifacts and are gitignored.
"""

from __future__ import annotations

import re
from collections import defaultdict
from datetime import date
from pathlib import Path

import sbom as sboms_
from dsl_model import ROOT, parse_model

HEADER = "<!-- GENERATED by scripts/generate_reports.py — do not edit. -->\n"


def grouped_section(title: str, systems, prop: str) -> str:
    groups = defaultdict(list)
    for system in systems:
        groups[system.properties.get(prop) or "(not set)"].append(system.name)
    lines = [f"### Systems by {title}", ""]
    for value in sorted(groups):
        lines.append(f"* **{value}**: {', '.join(sorted(groups[value]))}")
    lines.append("")
    return "\n".join(lines)


def technology_inventory(model) -> str:
    lines = [
        HEADER,
        "## Technology Inventory (generated)",
        "",
        f"_Generated from model properties on {date.today().isoformat()}._",
        "",
        "### All Systems",
        "",
        "| System | Capability | Owner | Runtime | Database | Hosting | Criticality |",
        "|---|---|---|---|---|---|---|",
    ]
    for system in sorted(model.systems, key=lambda s: s.name):
        p = system.properties.get
        lines.append(table_row(
            system.name, p("capability", "-"), p("owner", "-"), p("runtime", "-"),
            p("database", "-"), p("hosting", "-"), p("criticality", "-"),
        ))
    lines.append("")
    for prop, title in (
        ("runtime", "Runtime"),
        ("database", "Database"),
        ("hosting", "Hosting"),
        ("lifecycle", "Lifecycle"),
        ("criticality", "Criticality"),
        ("capability", "Capability"),
    ):
        lines.append(grouped_section(title, model.systems, prop))
    return "\n".join(lines)


def interface_catalogue(model) -> str:
    element_names = {s.identifier: s.name for s in model.systems}
    system_ids = set(element_names)

    lines = [
        HEADER,
        "## Interface Catalogue (generated)",
        "",
        f"_Generated from integration assets on {date.today().isoformat()}._",
        "",
        "| Source | Target | Description | Technology |",
        "|---|---|---|---|",
    ]
    for relationship in model.relationships:
        # System-to-system integrations only (the first-class integration assets).
        if relationship.source in system_ids and relationship.destination in system_ids:
            lines.append(table_row(
                element_names[relationship.source],
                element_names[relationship.destination],
                relationship.description,
                relationship.technology or "-",
            ))
    lines.append("")
    lines.append(interface_details())
    return "\n".join(lines)


def adr_body(text: str) -> tuple[str, str]:
    """Split an adr-tools Markdown ADR into (title, body).

    Section headings become bold labels rather than nested headings: these are
    already deep inside the catalogue, and Markdown has no level beyond
    '######'.
    """
    title = ""
    out = []
    for line in text.splitlines():
        if line.startswith("# ") and not title:
            # "1. Use event streaming ..." -> "Use event streaming ..."
            title = re.sub(r"^\d+\.\s*", "", line[2:].strip())
        elif line.startswith("## "):
            out += ["", f"**{line[3:].strip()}**", ""]
        else:
            out.append(line)
    body = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()
    return title, body


def table_row(*cells: str) -> str:
    """One Markdown table row; a literal '|' in a value would split the cell."""
    return "| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |"


def shift_headings(text: str, levels: int) -> str:
    """Demote every Markdown heading by `levels` (## Title -> #### Title),
    leaving fenced code blocks alone."""
    lines = []
    in_fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        elif line.startswith("#") and not in_fence:
            line = "#" * levels + line
        lines.append(line)
    return "\n".join(lines)


def interface_details() -> str:
    """Inline each integration's interface documentation and ADRs.

    Structurizr attaches documentation to elements, and integrations are
    relationships — so `!docs` cannot reach these files. Publishing them here
    keeps the authored content (authentication, classification, ownership,
    monitoring) visible in the portal while it stays owned by the integration
    asset folder.
    """
    integrations_dir = ROOT / "models/integrations"
    lines = ["### Interface Documentation", ""]

    for folder in sorted(p for p in integrations_dir.iterdir() if p.is_dir()):
        doc = folder / "docs" / "interface.md"
        if not doc.exists():
            continue

        # The doc's own "## Interface: A -> B" becomes "####", sitting under
        # this section; its inner headings follow at "#####".
        lines += [shift_headings(doc.read_text().strip(), 2), ""]

        adr_dir = folder / "adr"
        if adr_dir.is_dir():
            for adr in sorted(adr_dir.glob("*.md")):
                title, body = adr_body(adr.read_text().strip())
                lines += [f"##### Decision: {title}", "", body, ""]

        lines.append(f"_Source: `models/integrations/{folder.name}/`_")
        lines += ["", "---", ""]

    return "\n".join(lines)


def sbom_page(model, folder: Path, sboms) -> str:
    """One asset's SBOM page: a section per deployable, listing its components."""
    lines = [
        "## Software Bill of Materials",
        "",
        "<!-- GENERATED by scripts/generate_reports.py — edit the SBOM files instead. -->",
        "",
        f"_Generated from the CycloneDX files in `{folder.relative_to(ROOT).as_posix()}/sbom/`. "
        f"An SBOM older than {sboms_.MAX_AGE_DAYS} days is flagged as stale._",
        "",
    ]
    for sbom in sorted(sboms, key=lambda s: (s.element != s.system, s.element)):
        lines += [f"### {sboms_.element_name(model, sbom.element)}", ""]
        produced = str(sbom.produced) if sbom.produced else "unknown"
        if sbom.stale:
            produced += f" — **stale** ({sbom.age_days} days old)"
        lines += [
            "| Detail | Value |",
            "|---|---|",
            f"| Produced | {produced} |",
            f"| Tool | {sbom.tool or '-'} |",
            f"| Components | {len(sbom.components)} |",
            f"| File | `sbom/{sbom.path.name}` |",
            "",
            # Group in its own column: the portal search splits words only on
            # spaces and hyphens, so "group:name" would hide the name from it.
            "| Component | Group | Version | Licence | Ecosystem |",
            "|---|---|---|---|---|",
        ]
        for c in sorted(sbom.components, key=lambda c: (c.name.lower(), c.group)):
            lines.append(table_row(c.name, c.group or "-", c.version, c.licence, c.ecosystem))
        lines.append("")
    return "\n".join(lines)


def component_inventory(model, sboms) -> str:
    """Estate-wide view of the SBOMs: coverage per system, and every component
    with the systems that use it."""
    def where(sbom) -> str:
        system = sboms_.element_name(model, sbom.system)
        if sbom.element == sbom.system:
            return system
        return f"{system} ({sboms_.element_name(model, sbom.element)})"

    lines = [
        HEADER,
        "## Component Inventory (generated)",
        "",
        f"_Generated from the systems' SBOMs on {date.today().isoformat()}. "
        "Search the portal for a library name to find this page and the "
        "systems' own SBOM pages._",
        "",
        "### SBOM coverage",
        "",
        "| System | SBOMs | Produced | Status |",
        "|---|---|---|---|",
    ]
    by_system = defaultdict(list)
    for sbom in sboms:
        by_system[sbom.system].append(sbom)
    for system in sorted(model.systems, key=lambda s: s.name):
        found = by_system.get(system.identifier, [])
        if found:
            stale = [s for s in found if s.stale]
            status = (f"Stale — older than {sboms_.MAX_AGE_DAYS} days"
                      if stale else "Current")
            lines.append(table_row(
                system.name,
                ", ".join(f"`{s.path.name}`" for s in found),
                ", ".join(str(s.produced or "unknown") for s in found),
                status,
            ))
        else:
            lines.append(table_row(
                system.name, "-", "-", system.properties.get("sbom") or "**Missing**",
            ))
    lines.append("")

    usage = defaultdict(set)   # (name, group, version) -> where it is used
    licences = {}
    for sbom in sboms:
        for c in sbom.components:
            usage[(c.name, c.group, c.version)].add(where(sbom))
            licences[(c.name, c.group, c.version)] = c.licence
    lines += [
        "### Components",
        "",
        "Each version is listed separately, so a component used at two "
        "versions appears twice.",
        "",
        "| Component | Group | Version | Licence | Used by |",
        "|---|---|---|---|---|",
    ]
    for key in sorted(usage, key=lambda k: (k[0].lower(), k[1], k[2])):
        name, group, version = key
        lines.append(table_row(
            name, group or "-", version, licences[key], ", ".join(sorted(usage[key])),
        ))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    model = parse_model()
    outputs = {
        ROOT / "workspace/docs/90-technology-inventory.gen.md":
            technology_inventory(model),
        ROOT / "workspace/docs/91-interface-catalogue.gen.md":
            interface_catalogue(model),
    }

    # SBOMs: invalid files are reported by `make validate`; publish the rest.
    sboms = [s for s in sboms_.load(model) if not s.errors]
    outputs[ROOT / "workspace/docs/92-component-inventory.gen.md"] = \
        component_inventory(model, sboms)
    for old in ROOT.glob("models/**/docs/90-sbom.gen.md"):
        old.unlink()  # an asset whose SBOMs were removed must not keep a page
    by_folder = defaultdict(list)
    for sbom in sboms:
        by_folder[sboms_.asset_folder(sbom.path)].append(sbom)
    for folder, found in by_folder.items():
        outputs[folder / "docs" / "90-sbom.gen.md"] = sbom_page(model, folder, found)

    for path, content in outputs.items():
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
