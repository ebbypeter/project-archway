#!/usr/bin/env python3
"""Publish the repository-level documentation into the portal.

The Markdown under docs/ (practice standards, policies, capabilities) is not
attached to any Structurizr workspace, so site-generatr would never render it,
and Markdown has no include directive to pull it in from outside a workspace's
docs directory — so instead this script compiles each docs/ area into one
generated section of the Enterprise workspace documentation (headings shifted
down one level).

The files in docs/ remain the single source of truth; the *.gen.md outputs
are build artifacts and are gitignored.

Run by scripts/build_site.sh before site generation.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET_DIR = ROOT / "workspace/docs"

# (output file, section title, sources) — a source is a directory of .md
# files or a single .md file.
SECTIONS = [
    ("20-practice-standards.gen.md", "Architecture Practice Standards", [
        ROOT / "docs/architecture-as-code",
        # Governed by Architecture Practice and machine-read by the validator,
        # so it lives with the shared model rather than under docs/.
        ROOT / "models/shared/tags/approved-tags.md",
    ]),
    ("21-policies.gen.md", "Policies", [ROOT / "docs/policies"]),
    ("22-capabilities.gen.md", "Business Capabilities", [ROOT / "docs/capabilities"]),
]

HEADER = "<!-- GENERATED by scripts/aggregate_docs.py from {source} — edit there. -->\n"


def shift_headings(text: str) -> str:
    """Demote every Markdown heading one level (# Title -> ## Title).

    Lines inside fenced code blocks are left alone — a shell comment is not a
    heading.
    """
    lines = []
    in_fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        elif line.startswith("#") and not in_fence:
            line = "#" + line
        lines.append(line)
    return "\n".join(lines)


def main() -> None:
    for filename, title, sources in SECTIONS:
        parts = [
            HEADER.format(
                source=", ".join(s.relative_to(ROOT).as_posix() for s in sources)
            ),
            f"## {title}",
            "",
        ]
        for source in sources:
            docs = sorted(source.glob("*.md")) if source.is_dir() else [source]
            for doc in docs:
                parts.append(shift_headings(doc.read_text()).rstrip())
                parts.append("")
        target = TARGET_DIR / filename
        target.write_text("\n".join(parts))
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
